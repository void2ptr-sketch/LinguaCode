/**
 * Маппинг тоновых гласных → базовые буквы и номера тонов.
 * Единый источник данных для всей логики тоновых марок.
 */

/** Базовая гласная (без тона) → набор тоновых марок (1–4). Ключ 'ü' (не 'v'). */
export const VOWEL_TONE_MARKS: Readonly<Record<string, Record<1 | 2 | 3 | 4, string>>> = {
  a: { 1: '\u0101', 2: '\u00e1', 3: '\u01ce', 4: '\u00e0' },
  e: { 1: '\u0113', 2: '\u00e9', 3: '\u011b', 4: '\u00e8' },
  i: { 1: '\u012b', 2: '\u00ed', 3: '\u01d0', 4: '\u00ec' },
  o: { 1: '\u014d', 2: '\u00f3', 3: '\u01d2', 4: '\u00f2' },
  u: { 1: '\u016b', 2: '\u00fa', 3: '\u01d4', 4: '\u00f9' },
  ü: { 1: '\u01d6', 2: '\u01d8', 3: '\u01da', 4: '\u01dc' },
};

/** Тоновая гласная (с тоном) → базовая буква. */
export const TONE_MARK_TO_BASE: Record<string, string> = {
  '\u0101': 'a', '\u00e1': 'a', '\u01ce': 'a', '\u00e0': 'a',
  '\u0113': 'e', '\u00e9': 'e', '\u011b': 'e', '\u00e8': 'e',
  '\u012b': 'i', '\u00ed': 'i', '\u01d0': 'i', '\u00ec': 'i',
  '\u014d': 'o', '\u00f3': 'o', '\u01d2': 'o', '\u00f2': 'o',
  '\u016b': 'u', '\u00fa': 'u', '\u01d4': 'u', '\u00f9': 'u',
  '\u01d6': 'v', '\u01d8': 'v', '\u01da': 'v', '\u01dc': 'v',
};

/** Тоновая гласная → номер тона (1–4). Возвращает `null` для нетоновых символов. */
export function toneFromMarkedVowel(char: string): 1 | 2 | 3 | 4 | null {
  const toneByChar: Record<string, 1 | 2 | 3 | 4> = {
    '\u0101': 1, '\u00e1': 2, '\u01ce': 3, '\u00e0': 4,
    '\u0113': 1, '\u00e9': 2, '\u011b': 3, '\u00e8': 4,
    '\u012b': 1, '\u00ed': 2, '\u01d0': 3, '\u00ec': 4,
    '\u014d': 1, '\u00f3': 2, '\u01d2': 3, '\u00f2': 4,
    '\u016b': 1, '\u00fa': 2, '\u01d4': 3, '\u00f9': 4,
    '\u01d6': 1, '\u01d8': 2, '\u01da': 3, '\u01dc': 4,
  };

  return (toneByChar[char] ?? null) as 1 | 2 | 3 | 4 | null;
}
