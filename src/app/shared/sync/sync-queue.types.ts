/**
 * Типы очереди офлайн-мутаций (write-behind sync).
 *
 * Очередь хранит сериализуемые операции (kind + payload) в IndexedDB.
 * Когда сеть возвращается, операции воспроизводятся через зарегистрированный
 * исполнитель (`SyncQueueExecutor`).
 */

/**
 * Запись очереди синхронизации.
 *
 * `payload` должен быть сериализуемым (JSON-совместимым), так как запись
 * хранится в IndexedDB.
 */
export type SyncQueueEntry = {
  /** Уникальный идентификатор операции. */
  id: string;
  /** Вид операции, например `'card.create'`, `'course.update'`. */
  kind: string;
  /** Сериализуемые данные операции. */
  payload: unknown;
  /** Время постановки в очередь (epoch ms). */
  createdAt: number;
  /** Количество неудачных попыток воспроизведения. */
  attempts: number;
};

/**
 * Исполнитель операций очереди синхронизации.
 *
 * Регистрируется один раз при старте приложения (см. `SyncQueueBootstrap`).
 */
export type SyncQueueExecutor = {
  /**
   * Возвращает `true`, если исполнитель умеет обрабатывать операции данного вида.
   *
   * @param kind — вид операции
   */
  canHandle(kind: string): boolean;
  /**
   * Выполняет операцию. Должен бросить ошибку при неуспехе — очередь
   * увеличит счётчик попыток и повторит позже.
   *
   * @param entry — запись операции
   */
  run(entry: SyncQueueEntry): Promise<void>;
};

/** Максимальное число попыток воспроизведения до отбрасывания операции. */
export const MAX_SYNC_ATTEMPTS = 3;
